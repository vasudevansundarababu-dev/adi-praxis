def lp_solver_ceiling(achieved, optimum, tolerance=0.01):
    """True when an achieved objective is within tolerance of the optimum (maximisation)."""
    a, o = _num(achieved), _num(optimum)
    if a is None or o is None:
        return False
    return a >= o - abs(o) * tolerance - 1e-9


