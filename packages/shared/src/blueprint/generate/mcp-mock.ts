import type { HarborBlueprint } from '../schema';
import { fieldsFor, type ResolvedAnswers } from './answers';
import { pyStr, pyValue } from './escape';

/** Runtime paths shared by the mock, the verifiers and `solve.sh`. All are relative to `$HARBOR_ROOT` (default `/`). */
export const HARBOR_RUNTIME = {
  statePath: '/var/lib/harbor/env_state.json',
  outputRoot: '/workspace/outputs/',
  rewardPath: '/logs/verifier/reward.txt',
} as const;

/** `environment/mcp_mock.py`: the internal loopback MCP simulator with the SME's slider values (Stage 3). */
export function mcpMockPy(bp: HarborBlueprint, r: ResolvedAnswers): string {
  const sim = bp.step_3_mcp_simulators;
  const tools = Object.fromEntries(
    sim.tools.map((t) => [t.tool_id, { description: t.description, parameters: Object.fromEntries(t.parameters.map((p) => [p.name, p.type])) }]),
  );
  const widgets = Object.fromEntries(sim.widgets.map((w) => [w.key, w.archetype]));
  return `${MOCK_HEADER}
STUDIO_ID = ${pyStr(bp.studio_id)}
MAX_TURNS = ${pyValue(bp.domain_meta.horizon.max_turns)}
CADENCE_UNIT = ${pyStr(bp.domain_meta.horizon.cadence_unit)}

# Simulator parameters set by the SME (Stage 3 sliders).
PARAMETERS = ${pyValue(r.sliders)}

WIDGETS = ${pyValue(widgets)}

# Custom fields bound to mcp_mock.py.
FIELDS = ${pyValue(fieldsFor(bp, r, 'mcp_mock.py'))}

TOOLS = ${pyValue(tools)}

# Synthetic mock data accepted by the Admin (authored_content.mcp_mock_seed_rows).
SEED_ROWS = ${pyValue(bp.authored_content.mcp_mock_seed_rows)}
${MOCK_BODY}`;
}

const MOCK_HEADER = `"""Hermetic MCP mock for one Harbor task (internal loopback only, no network).

Generated by the ADI Praxis Meta-Compiler. Do not edit: regenerate from the template blueprint.

Usage:
  python3 mcp_mock.py list                     list the tools as JSON
  python3 mcp_mock.py call <tool_id> '<json>'  call a tool with JSON arguments
  python3 mcp_mock.py serve                    JSON-RPC 2.0 over stdio (initialize, tools/list, tools/call)

Every successful call is recorded in the environment state that the verifiers read.
"""

import difflib
import json
import os
import sys

ROOT = os.environ.get("HARBOR_ROOT", "/")
STATE_PATH = os.path.join(ROOT, ${pyStr(HARBOR_RUNTIME.statePath.slice(1))})
`;

const MOCK_BODY = `

def diminishing_returns(spend, k_half):
    """Share of the maximum response at spend s: s / (s + K_half)."""
    spend = float(spend)
    k_half = float(k_half)
    if spend <= 0 or spend + k_half <= 0:
        return 0.0
    return spend / (spend + k_half)


def fuzzy_match(a, b, threshold):
    """True when two values are at least \`threshold\` similar (0-1, or 0-100 as a percentage)."""
    threshold = float(threshold)
    if threshold > 1:
        threshold = threshold / 100.0
    ratio = difflib.SequenceMatcher(None, str(a).strip().lower(), str(b).strip().lower()).ratio()
    return ratio >= threshold


def load_state():
    try:
        with open(STATE_PATH, encoding="utf-8") as f:
            state = json.load(f)
    except (OSError, ValueError):
        state = {}
    if not isinstance(state, dict):
        state = {}
    state.setdefault("turn", 0)
    state.setdefault("calls", [])
    return state


def save_state(state):
    os.makedirs(os.path.dirname(STATE_PATH), exist_ok=True)
    tmp = STATE_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(state, f, sort_keys=True, indent=2)
    os.replace(tmp, STATE_PATH)


_TYPES = {
    "string": lambda v: isinstance(v, str),
    "number": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
}


def _matches(row_value, wanted):
    for key, archetype in sorted(WIDGETS.items()):
        if archetype == "fuzzy_match_threshold_slider" and isinstance(wanted, str):
            return fuzzy_match(row_value, wanted, PARAMETERS[key])
    if isinstance(wanted, str) and isinstance(row_value, str):
        return row_value.strip().lower() == wanted.strip().lower()
    return row_value == wanted


def call_tool(tool_id, args):
    tool = TOOLS.get(tool_id)
    if tool is None:
        return {"ok": False, "error": "unknown tool"}
    if not isinstance(args, dict):
        return {"ok": False, "error": "arguments must be a JSON object"}
    for name, value in sorted(args.items()):
        expected = tool["parameters"].get(name)
        if expected is None:
            return {"ok": False, "error": "unknown parameter: " + name}
        if not _TYPES[expected](value):
            return {"ok": False, "error": "parameter " + name + " must be a " + expected}
    state = load_state()
    state["turn"] += 1
    state["calls"].append({"tool": tool_id, "args": args, "turn": state["turn"]})
    save_state(state)
    keys = [k for k in sorted(args) if any(k in row for row in SEED_ROWS)]
    rows = [row for row in SEED_ROWS if keys and all(k in row and _matches(row[k], args[k]) for k in keys)]
    curves = {}
    for key, archetype in sorted(WIDGETS.items()):
        if archetype != "diminishing_returns_curve_slider":
            continue
        for name, value in sorted(args.items()):
            if _TYPES["number"](value):
                curves.setdefault(key, {})[name] = round(diminishing_returns(value, PARAMETERS[key]), 6)
    return {"ok": True, "tool": tool_id, "turn": state["turn"], "rows": rows, "curves": curves}


def list_tools():
    return [
        {
            "name": tool_id,
            "description": tool["description"],
            "inputSchema": {
                "type": "object",
                "properties": {name: {"type": kind} for name, kind in sorted(tool["parameters"].items())},
                "additionalProperties": False,
            },
        }
        for tool_id, tool in sorted(TOOLS.items())
    ]


def serve(stdin=sys.stdin, stdout=sys.stdout):
    for line in stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except ValueError:
            continue
        method = req.get("method")
        if method == "initialize":
            result = {"protocolVersion": "2024-11-05", "serverInfo": {"name": "praxis-harbor-mock", "version": STUDIO_ID}, "capabilities": {"tools": {}}}
        elif method == "tools/list":
            result = {"tools": list_tools()}
        elif method == "tools/call":
            params = req.get("params") or {}
            out = call_tool(params.get("name"), params.get("arguments") or {})
            result = {"content": [{"type": "text", "text": json.dumps(out, sort_keys=True)}], "isError": not out["ok"]}
        else:
            if "id" in req:
                stdout.write(json.dumps({"jsonrpc": "2.0", "id": req["id"], "error": {"code": -32601, "message": "method not found"}}) + "\\n")
                stdout.flush()
            continue
        if "id" in req:
            stdout.write(json.dumps({"jsonrpc": "2.0", "id": req["id"], "result": result}, sort_keys=True) + "\\n")
            stdout.flush()


def main(argv):
    if len(argv) >= 2 and argv[1] == "list":
        print(json.dumps(list_tools(), indent=2, sort_keys=True))
        return 0
    if len(argv) >= 3 and argv[1] == "call":
        out = call_tool(argv[2], json.loads(argv[3]) if len(argv) > 3 else {})
        print(json.dumps(out, indent=2, sort_keys=True))
        return 0 if out["ok"] else 1
    if len(argv) >= 2 and argv[1] == "serve":
        serve()
        return 0
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
`;
