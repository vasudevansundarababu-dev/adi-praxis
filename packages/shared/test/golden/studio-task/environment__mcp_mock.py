def diminishing_returns(spend, k_half):
    """Share of the maximum response at spend s: s / (s + K_half)."""
    spend = float(spend)
    k_half = float(k_half)
    if spend <= 0 or spend + k_half <= 0:
        return 0.0
    return spend / (spend + k_half)


def fuzzy_match(a, b, threshold):
    """True when two values are at least `threshold` similar (0-1, or 0-100 as a percentage)."""
    threshold = float(threshold)
    if threshold > 1:
        threshold = threshold / 100.0
    ratio = difflib.SequenceMatcher(None, str(a).strip().lower(), str(b).strip().lower()).ratio()
    return ratio >= threshold


