import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { expect, test } from '@playwright/test';

test('manual answers redact sensitive identifiers and cleared answers cannot be submitted (#47 #76 #78)', async ({ page, request }) => {
  test.skip(!!process.env.E2E_WEB_URL, 'local isolated fixtures only; no paid calls');
  const base = 'http://localhost:3300/api/v1';
  const post = async (path: string, data: object = {}) => {
    const response = await request.post(base + path, { data, headers: { 'idempotency-key': randomUUID() } });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  await post('/auth/login', { email: 'admin@e2e.local', password: 'e2e-admin-password' });
  const domain = await post('/domains', { name: 'Banking ' + randomUUID().slice(0, 8) });
  const template = await post('/templates', { domainId: domain.id, workflowName: 'KYC onboarding', primaryWork: 'x', verificationCriteria: 'x', humanGate: 'x', defaultTptMinutes: 60, skills: ['KYC'], taskModes: ['AUTHORING'] });
  await post(`/templates/${template.id}/publish`);
  const jd = await post('/job-descriptions', { title: 'KYC author', responsibilities: 'Author synthetic cases.', skills: ['KYC'], wagePerTask: 1, wageCurrency: 'USD', locationType: 'REMOTE' });
  const date = (days: number) => new Date(Date.now() + days * 86400000).toISOString().slice(0, 10);
  const project = await post('/projects', { templateId: template.id, name: 'FORM REGRESSION ' + randomUUID(), distinctTarget: 8, maxPerExpert: 4, tptMinutes: 60, startDate: date(1), endDate: date(30), jobDescriptionId: jd.id, demographicFilters: [{ attributeKey: 'country', operator: 'IN', values: ['GB'], required: true }] });
  for (const action of ['submit', 'match', 'opportunity/publish']) await post(`/projects/${project.id}/${action}`);
  const detail = await (await request.get(base + `/projects/${project.id}/opportunity`)).json();
  const candidateBase = 'http://localhost:3301';
  const cp = async (path: string, data: object = {}) => {
    const response = await page.request.post(candidateBase + '/api/v1' + path, { data, headers: { 'idempotency-key': randomUUID() } });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  const token = await cp('/auth/dev/google-token', { email: `form.${randomUUID()}@example.test`, name: 'Form Tester' });
  const signed = await cp('/auth/google', { credential: token.credential, adultAttested: true });
  const enrollment = await cp('/me/enrollments', { opportunityId: detail.opportunityId });
  const path = `${candidateBase}/enrollments/${enrollment.id}`;
  await page.goto(path + '/form');
  const answer = page.locator('#f-work_example');
  await expect(answer).toBeVisible();
  await answer.fill('Checked account 12345678 and PAN ABCDE1234F.');
  await page.getByRole('button', { name: 'Save answers' }).click();
  await expect(page.getByRole('status')).toContainText('sensitive identifiers removed');
  await expect(answer).not.toHaveValue(/12345678|ABCDE1234F/);
  await expect(answer).toHaveValue(/\[removed:/);
  await answer.fill('A generic synthetic case.');
  await page.getByRole('button', { name: 'Save answers' }).click();
  await expect(page.getByRole('status')).toHaveText('Saved.');
  await answer.fill('');
  await page.getByRole('button', { name: 'Save answers' }).click();
  await expect(page.getByRole('status')).toHaveText('Saved.');
  await page.goto(path + '/review');
  await expect(page.getByRole('button', { name: 'Confirm and submit', exact: true })).toBeDisabled();
  let releaseUpload!: () => void;
  let uploads = 0;
  const held = new Promise<void>((resolve) => { releaseUpload = resolve; });
  await page.route('**/api/v1/me/evidence', async (route) => {
    uploads++;
    await held;
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Controlled upload failure' }) });
  });
  await page.getByLabel('I have permission to share these files for qualification review.').check();
  await page.getByLabel('Evidence file').setInputFiles({ name: 'oversized.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(12 * 1024 * 1024) });
  await expect(page.getByText('This file is larger than 10 MB. Choose a smaller file.', { exact: true })).toBeVisible();
  expect(uploads).toBe(0);
  await expect(page.getByRole('progressbar')).toHaveCount(0);
  await page.getByLabel('Evidence file').setInputFiles({ name: 'synthetic.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 synthetic fixture') });
  await expect(page.getByRole('progressbar', { name: 'Evidence upload in progress' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Confirm and submit', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Submitting…', exact: true })).toHaveCount(0);
  releaseUpload();
  await expect(page.getByRole('progressbar')).toHaveCount(0);
  await expect(page.getByText('Controlled upload failure', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Evidence file')).toBeEnabled();
  await expect(page.getByLabel('Evidence file')).toHaveValue('');
  await page.getByLabel('Evidence file').setInputFiles({ name: 'synthetic.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 synthetic fixture') });
  await expect.poll(() => uploads).toBe(2);
  await page.goto(path + '/form');
  await expect(answer).toHaveValue('');
  const saved = await (await page.request.get(candidateBase + '/api/v1/me/enrollments/' + enrollment.id + '/conversation')).json();
  expect(saved.profile.fields.work_example).toBeUndefined();
  expect(saved.readiness.canSubmit).toBe(false);
  await page.goto(path + '/status');
  await expect(page.getByRole('link', { name: 'Continue your draft profile', exact: true })).toBeVisible();
  const progress = page.getByRole('list', { name: 'Your progress' });
  await expect(progress.locator('li').nth(0)).toHaveAttribute('data-state', 'current');
  await expect(progress.locator('li').nth(1)).toHaveAttribute('data-state', 'todo');
  const identitySession = await cp('/me/identity/session');
  const identityId = new URL(identitySession.url).pathname.split('/').pop();
  await cp(`/dev/identity/${identityId}/simulate`, { status: 'verified', adult: true });
  const fields = [...new Set<string>(saved.questions.flatMap((q: { fields: string[] }) => q.fields).filter((key: string) => key !== 'roles'))];
  const complete = await cp('/me/profile/corrections', { enrollmentId: enrollment.id, expectedRevision: saved.session.revision,
    fields: fields.map((fieldKey) => ({ fieldKey, action: 'EDIT', value: fieldKey.endsWith('_years') || fieldKey === 'hours_per_week' ? 10 : `Generic answer for ${fieldKey}` })),
    roles: [{ action: 'ADD', role: { title: 'KYC analyst', start: '2020-01', end: null } }],
  });
  await cp(`/me/enrollments/${enrollment.id}/submit`, { expectedRevision: complete.session.revision, confirmAccuracy: true, evidencePermission: true });
  await page.goto(path + '/review');
  await expect(page.getByRole('heading', { name: 'Profile submitted', exact: true })).toBeVisible();
  await expect(page.getByText(/was submitted on \d{1,2} [A-Z][a-z]{2,3} \d{4} \(UTC\)/)).toBeVisible();
  // The existing guarded e2e-only fixture supplies the unrelated selection precondition.
  execFileSync('pnpm', ['--silent', '--filter', '@praxis/api', 'exec', 'tsx', 'scripts/e2e-m10.ts', 'select', signed.id], { encoding: 'utf8' });
  await page.goto(path + '/onboarding');
  await page.getByRole('button', { name: /Work preferences/ }).click();
  await page.getByLabel('Country you work from', { exact: false }).selectOption('GB');
  await page.getByLabel('Time zone', { exact: false }).selectOption('Europe/London');
  await page.getByRole('button', { name: 'Add a language', exact: true }).click();
  const secondLanguage = page.getByRole('combobox', { name: 'Language 2', exact: true });
  expect(await secondLanguage.inputValue()).not.toBe('en');
  await expect(secondLanguage.locator('option[value="en"]')).toHaveAttribute('disabled', '');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: /Work preferences Done/ })).toBeVisible();
  const minorToken = await cp('/auth/dev/google-token', { email: `minor.${randomUUID()}@example.test`, name: 'Age check fixture' });
  await cp('/auth/google', { credential: minorToken.credential, adultAttested: true });
  const minorSession = await cp('/me/identity/session');
  const minorId = new URL(minorSession.url).pathname.split('/').pop();
  await cp(`/dev/identity/${minorId}/simulate`, { status: 'verified', adult: false });
  await page.goto(`${candidateBase}/opportunities/${detail.opportunityId}?start=1`);
  await expect(page.getByText('Contributors must be 18 or over. This is not a judgement about your expertise.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /Apply: build my SME profile/ })).toHaveCount(0);
  const withdrawnToken = await cp('/auth/dev/google-token', { email: `withdrawn.${randomUUID()}@example.test`, name: 'Withdrawn draft fixture' });
  await cp('/auth/google', { credential: withdrawnToken.credential, adultAttested: true });
  const withdrawn = await cp('/me/enrollments', { opportunityId: detail.opportunityId });
  await cp(`/me/enrollments/${withdrawn.id}/withdraw`);
  await page.goto(`${candidateBase}/enrollments/${withdrawn.id}/status`);
  await expect(page.getByRole('link', { name: 'View your saved draft profile', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'View the profile you submitted', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'View your saved draft profile', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Saved draft profile', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Profile submitted', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Add role', exact: true })).toHaveCount(0);
});
