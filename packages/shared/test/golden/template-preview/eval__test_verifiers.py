def _num(v):
    if isinstance(v, bool):
        return None
    try:
        n = float(v)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(n) else n


def _norm(v):
    return str(v).strip().lower()


def triggered(rule, value):
    """True when one value meets the rule's IF condition."""
    op, threshold = rule["operator"], rule["threshold"]
    if op == "GREATER_THAN":
        n = _num(value)
        return n is not None and n > float(threshold)
    if op == "EQUALS":
        a, b = _num(value), _num(threshold)
        if a is not None and b is not None:
            return a == b
        return _norm(value) == _norm(threshold)
    if op == "CONTAINS_ANY":
        if isinstance(value, str):
            return any(_norm(t) in _norm(value) for t in threshold)
        if isinstance(value, (list, tuple, set)):
            return any(_norm(v) == _norm(t) for v in value for t in threshold)
        return any(_norm(value) == _norm(t) for t in threshold)
    return False


