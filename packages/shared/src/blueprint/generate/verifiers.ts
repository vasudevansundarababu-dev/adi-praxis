/** Rule text used in docstrings, the instruction and the studio: "IF subject OP threshold THEN HARD_FAIL (-1.0)". */
export function ruleSummary(r: HarborBlueprint['step_4_invariant_catalog']['rules'][number]): string {
  const t = Array.isArray(r.threshold) ? `[${r.threshold.join(', ')}]` : String(r.threshold);
  return `IF ${r.subject} ${r.operator} ${t} THEN ${r.penalty} (-1.0)`;
}

/** Python source lines as a readable `"\n".join([...])` expression, one string literal per line. */
function pyLines(source: string, indent: number): string {
  const lines = splitLines(source.replace(/\s+$/, ''));
  if (lines.length === 1 && lines[0] === '') return '""';
  const pad = ' '.repeat(indent + 4);
  return `"\\n".join([\n${lines.map((l) => `${pad}${pyStr(l)},`).join('\n')}\n${' '.repeat(indent)}])`;
}

/**
 * `eval/test_verifiers.py` (Stages 4, 5 and verifier-bound custom fields). Hidden from the agent.
 *
 * Scoring (written to `$HARBOR_REWARD_PATH` when the session ends): any enabled invariant triggered gives -1.0;
 * otherwise any failed custom assertion gives 0.0; otherwise the sum of the weights of the passed milestones / 100.
 * Assertions and milestone bodies are compiled from string literals (`eval` and `exec` mode), so blueprint text
 * cannot change the structure of this file.
 */
export function testVerifiersPy(bp: HarborBlueprint, r: ResolvedAnswers): string {
  const rules = bp.step_4_invariant_catalog.rules.filter((x) => r.enabledRuleIds.includes(x.id));
  const milestones = bp.step_5_default_rubric.milestones;
  const bound = allCustomFields(bp).filter((f) => f.inject_into.includes('eval/test_verifiers.py'));
  const taken = new Set<string>();

  const invariantTests = rules.map((rule) => {
    const name = `test_invariant_${pyIdent(rule.id, taken)}`;
    return `def ${name}(env_state):
    ${pyStr(ruleSummary(rule))}
    with _Outcome(${pyStr(`invariant:${rule.id}`)}):
        rule = INVARIANTS[${pyStr(rule.id)}]
        hits = [v for v in subject_values(env_state, rule["subject"]) if triggered(rule, v)]
        assert not hits, "guardrail triggered: %r" % (hits[:5],)
`;
  });

  const milestoneTests = milestones.map((m) => {
    const name = `test_milestone_${pyIdent(m.id, taken)}`;
    return `def ${name}(env_state, ground_truth, params, fields):
    ${pyStr(`${m.label} (weight ${r.milestoneWeights[m.id]}, ${m.verifier_template})`)}
    with _Outcome(${pyStr(`milestone:${m.id}`)}):
        _run_body(${pyStr(m.id)}, env_state, ground_truth, params, fields)
`;
  });

  const customTests = bound.map(
    (f) => `def test_custom_${f.field_id}(env_state):
    ${pyStr(f.label)}
    with _Outcome(${pyStr(`custom:${f.field_id}`)}):
        value = FIELDS[${pyStr(f.field_id)}]
        assert _check(${pyStr(f.verifier_assertion)}, env_state, value), ${pyStr(`custom assertion failed: ${f.field_id}`)}
`,
  );

  const invariants = Object.fromEntries(rules.map((x) => [x.id, { subject: x.subject, operator: x.operator, threshold: x.threshold, penalty: x.penalty }]));
  const ms = Object.fromEntries(milestones.map((m) => [m.id, { label: m.label, weight: r.milestoneWeights[m.id], verifier_template: m.verifier_template }]));
  const bodies = milestones.length
    ? `{\n${milestones.map((m) => `    ${pyStr(m.id)}: ${pyLines(m.verifier_body, 4)},`).join('\n')}\n}`
    : '{}';

  return `${VERIFIER_HEADER}
STUDIO_ID = ${pyStr(bp.studio_id)}

# Simulator parameters (Stage 3 sliders) and custom fields bound to eval/test_verifiers.py.
PARAMS = ${pyValue(r.sliders)}

FIELDS = ${pyValue(fieldsFor(bp, r, 'eval/test_verifiers.py'))}

# Enabled guardrails (Stage 4). Any trigger is a hard fail: score -1.0.
INVARIANTS = ${pyValue(invariants)}

# Rubric milestones (Stage 5) with the weights in use; they sum to 100.
MILESTONES = ${pyValue(ms)}

# Verifier bodies accepted by the Admin, run with env_state, ground_truth, params, fields and the helpers below.
MILESTONE_BODIES = ${bodies}

CUSTOM_ASSERTIONS = ${pyValue(Object.fromEntries(bound.map((f) => [f.field_id, f.verifier_assertion])))}
${VERIFIER_RUNTIME}
${['# Guardrails (Stage 4)', ...invariantTests, '# Rubric milestones (Stage 5)', ...milestoneTests, '# Custom fields bound to eval/test_verifiers.py (S2-09)', ...customTests].join('\n\n')}`;
}

