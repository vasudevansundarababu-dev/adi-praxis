// Generates the tester package's tables from docs/testing/data/*.mjs and the API route files:
//   TEST-CASES.md, test-cases.csv, DECISION-REGISTER.md, API-QUICK-REFERENCE.md
// Run from the repository root:  node docs/testing/build.mjs
// Fails if a test case id is duplicated or a case refers to an unknown decision.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DECISIONS } from './data/decisions.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const ORDER = ['e2e', 'sme', 'pm', 'admin', 'reviewer', 'partner', 'finance', 'rlgym', 'nfr', 'security', 'pentest'];
const GROUP = { e2e: 'End-to-end journeys', sme: 'SME / candidate', pm: 'Project manager', admin: 'Admin', reviewer: 'Validator (Reviewer role)', partner: 'Partner (partner portal)', finance: 'Finance', rlgym: 'RL Gym (API client)', nfr: 'Non-functional', security: 'Security (browser checks)', pentest: 'Penetration testing' };

const groups = [];
for (const key of ORDER) {
  const { CASES } = await import(`./data/cases-${key}.mjs`);
  groups.push({ key, title: GROUP[key], cases: CASES });
}
const all = groups.flatMap((g) => g.cases.map((c) => ({ ...c, group: g.title })));

// ── Validation ──
const problems = [];
const ids = new Set();
const decisionIds = new Set(DECISIONS.map((d) => d.id));
if (decisionIds.size !== DECISIONS.length) problems.push('Duplicate decision id');
for (const c of all) {
  if (ids.has(c.id)) problems.push(`Duplicate test case id ${c.id}`);
  ids.add(c.id);
  for (const d of c.decisions ?? []) if (!decisionIds.has(d)) problems.push(`${c.id} refers to unknown decision ${d}`);
  for (const k of ['priority', 'category', 'pre', 'steps', 'expected']) if (!c[k] || (Array.isArray(c[k]) && !c[k].length)) problems.push(`${c.id} has no ${k}`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const md = (s) => String(s).replace(/\|/g, '\\|');
const count = (f) => all.filter(f).length;
const casesFor = (id) => all.filter((c) => (c.decisions ?? []).includes(id)).map((c) => c.id);
// GitHub's heading anchor: lower case, punctuation removed, spaces to hyphens.
const slug = (text) => text.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');
const caseAnchor = (id) => { const c = all.find((x) => x.id === id); return c ? slug(`${c.id} ${c.title}`) : id.toLowerCase(); };
const header = (title) => `<!-- Generated by docs/testing/build.mjs from docs/testing/data. Edit the data files, not this file. -->\n\n# ${title}\n\n`;

// ── TEST-CASES.md ──
let out = header('ADI Praxis test cases');
out += `${all.length} test cases. Priorities: **P1** must pass before production, **P2** should pass, **P3** nice to have. Categories: E2E end-to-end, FUNC functional, UX user experience, NFR non-functional, SEC security, PEN penetration testing.\n\n`;
out += 'Before you start, read [README.md](README.md) (environment, accounts, samples, how to report). Record every run in `test-cases.csv` (a copy per tester or a shared sheet).\n\n';
out += 'Release 1.1: the internal Reviewer role is shown as **Validator** on screen; in cases written for 1.0, "Reviewer" means the Validator. New in 1.1: the Partner and Finance groups, and the cases numbered TC-E2E-008 onwards, TC-SME-060 onwards, TC-PM-013 onwards, TC-ADM-013 onwards, TC-REV-030 onwards, TC-NFR-050 onwards, TC-SEC-019 onwards and TC-PEN-018 onwards. See [WHATS-NEW-1.1.md](WHATS-NEW-1.1.md) for the day 1 order. Added by the coverage audit of 1 Oct 2026 (API-only Admin functions, permissions per role, remaining screens): TC-E2E-012, TC-SME-076 onwards, TC-PM-020 onwards, TC-ADM-023 onwards, TC-REV-036 onwards, TC-PTR-016, TC-FIN-013 and TC-SEC-028. [COVERAGE.md](COVERAGE.md) maps every screen, role and Admin function to its cases.\n\n';
out += '| Group | Cases | P1 | P2 | P3 |\n| --- | ---: | ---: | ---: | ---: |\n';
for (const g of groups) out += `| [${g.title}](#${g.title.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) | ${g.cases.length} | ${g.cases.filter((c) => c.priority === 'P1').length} | ${g.cases.filter((c) => c.priority === 'P2').length} | ${g.cases.filter((c) => c.priority === 'P3').length} |\n`;
out += `| **Total** | **${all.length}** | **${count((c) => c.priority === 'P1')}** | **${count((c) => c.priority === 'P2')}** | **${count((c) => c.priority === 'P3')}** |\n\n`;
for (const g of groups) {
  out += `## ${g.title}\n\n`;
  for (const c of g.cases) {
    out += `### ${c.id} ${c.title}\n\n`;
    out += `**Persona:** ${c.persona} · **Category:** ${c.category} · **Priority:** ${c.priority}${c.decisions?.length ? ` · **Decisions:** ${c.decisions.map((d) => `[${d}](DECISION-REGISTER.md#${d.toLowerCase()})`).join(', ')}` : ''}\n\n`;
    out += `**Before you start:** ${c.pre}\n\n**Steps**\n\n${c.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n**Expected**\n\n${c.expected.map((e) => `- ${e}`).join('\n')}\n\n`;
  }
}
writeFileSync(join(here, 'TEST-CASES.md'), out);

// ── test-cases.csv ──
const csv = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const cols = ['ID', 'Group', 'Persona', 'Category', 'Priority', 'Title', 'Before you start', 'Steps', 'Expected', 'Decisions', 'Status (Pass/Fail/Blocked/Not run)', 'Tester', 'Date (IST)', 'Build', 'Issue link', 'Notes'];
const rows = [cols.map(csv).join(',')];
for (const c of all) rows.push([c.id, c.group, c.persona, c.category, c.priority, c.title, c.pre, c.steps.map((s, i) => `${i + 1}. ${s}`).join('\n'), c.expected.map((e) => `- ${e}`).join('\n'), (c.decisions ?? []).join(' '), 'Not run', '', '', '', '', ''].map(csv).join(','));
// UTF-8 BOM so Excel shows non-English text (e.g. Devanagari, Tamil) correctly.
writeFileSync(join(here, 'test-cases.csv'), '﻿' + rows.join('\r\n') + '\r\n');

// ── DECISION-REGISTER.md ──
let dr = header('Decision register');
dr += 'Every product decision made while building ADI Praxis, written as what you should see. Test both whether the product does what was decided, and whether the decision itself is right for users. If you disagree with a decision, raise an **Enhancement request** naming the decision id; the product owner decides.\n\n';
dr += '**Decided by:** owner = the product owner; spec = the written specification; claude = chosen by Claude during the build where the spec was silent (look at these most critically).\n\n';
dr += '| Id | Area | Decided by | Decision | Test cases |\n| --- | --- | --- | --- | --- |\n';
for (const d of DECISIONS) dr += `| [${d.id}](#${d.id.toLowerCase()}) | ${d.area} | ${d.by} | ${md(d.decision)} | ${casesFor(d.id).join(', ') || '—'} |\n`;
dr += '\n';
for (const d of DECISIONS) {
  const cs = casesFor(d.id);
  dr += `## ${d.id}\n\n**${d.area}** · decided by ${d.by}\n\n${d.decision}\n\n**What you should see:** ${d.see}\n\n**Tested by:** ${cs.length ? cs.map((x) => `[${x}](TEST-CASES.md#${caseAnchor(x)})`).join(', ') : '— (exploratory testing only)'}\n\n`;
}
writeFileSync(join(here, 'DECISION-REGISTER.md'), dr);

// ── API-QUICK-REFERENCE.md (method, path, who may call it) ──
const routesDir = join(root, 'apps/api/src/routes');
const api = [];
const sources = [...readdirSync(routesDir).filter((x) => x.endsWith('.ts')).map((f) => [f, join(routesDir, f)]), ['app.ts', join(root, 'apps/api/src/app.ts')]];
for (const [f, file] of sources) {
  const src = readFileSync(file, 'utf8');
  const consts = Object.fromEntries([...src.matchAll(/const (\w+) = (\[[^\]]*\]|\{[^}]*\}|'[^']*')(?: as const)?;/g)].map((m) => [m[1], m[2]]));
  // Paths may be plain strings or template literals; `${path}` routes are expanded from the file's transition('…') calls
  // (projects.ts registers /projects/:id/cancel, /pause and /resume this way).
  const re = /(?:app|hook|v1)\.(get|post|put|patch|delete)\(\s*['`]([^'`]+)['`]\s*,\s*\{[\s\S]{0,300}?access:\s*([A-Za-z_]+|\[[^\]]*\]|\{[^}]*\}|'[^']*')/g;
  const transitions = [...src.matchAll(/transition\('(\w+)'/g)].map((m) => m[1]);
  for (const m of src.matchAll(re)) {
    let access = consts[m[3]] ?? m[3];
    // Constants used inside an access object, e.g. { roles: ACCESS, apiClient: 'CLIENT_API' }.
    if (access.startsWith('{')) access = access.replace(/(roles:\s*)([A-Z][A-Z_]+)\b/, (all, k, w) => (consts[w] ? `${k}${consts[w]}` : all));
    access = access.replace(/ as const/g, '').replace(/[[\]']/g, '').replace(/\s+/g, ' ').trim();
    if (access.startsWith('{')) access = access.replace(/[{}]/g, '').trim().replace(/roles: /, '').replace(/, apiClient: /, ', key ').replace(/^partnerScope: /, 'Partner API token, scope ').trim();
    // Health routes sit outside /api/v1; the Partner API v1 is registered under /partner/v1 (app.ts); the mock sign-in
    // and identity routes exist only in demo/test.
    const prefix = f === 'health.ts' ? '' : f === 'partner-api.ts' ? '/partner/v1' : '/api/v1';
    const paths = m[2].includes('${path}') ? transitions.map((t) => m[2].replace('${path}', t)) : [m[2]];
    for (const p of paths) {
      const mockOnly = /\/dev\//.test(p);
      api.push({ method: m[1].toUpperCase(), path: `${prefix}${p}`, access: mockOnly ? `${access} (demo/test only)` : access, file: f });
    }
  }
}
api.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
let ar = header('API quick reference');
ar += `All ${api.length} endpoints with who may call them, generated from the route code. Interactive documentation: \`<API URL>/docs\`. State changes (POST, PUT, PATCH, DELETE) need an \`Idempotency-Key\` header with a new UUID. Browser calls use the session cookie; RL Gym and client systems use \`Authorization: Bearer <key>\`.\n\n`;
ar += 'Access: `public` anyone · `authenticated` any signed-in console user · `candidate` a signed-in SME · `partner` a signed-in partner portal user (cookie `praxis_partner`) · role names = console roles (`REVIEWER` is shown as Validator) · `key RL_GYM` / `key CLIENT_API` = machine keys from Admin → API clients · `Partner API token, scope …` = an OAuth token from `POST /partner/v1/oauth/token` with that scope.\n\n';
ar += '**The Partner API v1 is under `/partner/v1` on the API host, not under `/api/v1`.** The partner portal (browser) uses `/api/v1/partner-portal/…`.\n\n';
ar += '| Method | Path | Who may call it | Source |\n| --- | --- | --- | --- |\n';
for (const r of api) ar += `| ${r.method} | \`${r.path}\` | ${md(r.access)} | ${r.file} |\n`;
writeFileSync(join(here, 'API-QUICK-REFERENCE.md'), ar);

// ── COVERAGE.md (traceability: screens, roles, Admin functions → test cases) ──
const { SCREENS, ADMIN_FUNCTIONS, ROLES, RULES, GAPS } = await import('./data/coverage.mjs');
const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : e.name === 'page.tsx' ? [join(dir, e.name)] : []));
const routeOf = (appDir, file) => {
  const segs = file.slice(appDir.length + 1).split('/').slice(0, -1).filter((s) => !/^\(.*\)$/.test(s)).map((s) => s.replace(/^\[(.+)\]$/, ':$1'));
  return `/${segs.join('/')}`;
};
const pages = [
  ...walk(join(root, 'apps/web/app')).map((f) => routeOf(join(root, 'apps/web/app'), f)).map((r) => ({ app: r === '/partner' || r.startsWith('/partner/') ? 'partner' : 'console', route: r })),
  ...walk(join(root, 'apps/candidate/app')).map((f) => ({ app: 'candidate', route: routeOf(join(root, 'apps/candidate/app'), f) })),
];
const covProblems = [];
const known = (list, where) => list.forEach((id) => ids.has(id) || covProblems.push(`coverage.mjs: unknown case ${id} (${where})`));
for (const s of SCREENS) {
  known(s.cases, s.route);
  if (!pages.some((p) => p.app === s.app && p.route === s.route)) covProblems.push(`coverage.mjs: no page file for ${s.app} ${s.route}`);
}
for (const f of ADMIN_FUNCTIONS) known(f.cases, f.fn);
for (const r of ROLES) known([...r.menu, ...r.denial], r.role);
for (const r of RULES) known(r.cases, r.rule);
if (covProblems.length) {
  console.error(covProblems.join('\n'));
  process.exit(1);
}
const unmapped = pages.filter((p) => !SCREENS.some((s) => s.app === p.app && s.route === p.route));
const link = (id) => `[${id}](TEST-CASES.md#${caseAnchor(id)})`;
const links = (list) => (list.length ? list.map(link).join(', ') : '**none**');
const APP_TITLE = { console: 'Console (Admin, PM, Validator, Finance)', partner: 'Partner portal', candidate: 'Candidate app (SMEs)' };
let cv = header('Test coverage (Release 1.1)');
cv += 'Which test cases cover each screen, role and Admin function. Generated from `docs/testing/data/coverage.mjs`; the build fails if a case id is unknown, and lists below any page in the code that has no entry. Sources: [the user guide](../user-guide/README.md), [ROLES-AND-ADMIN.md](../user-guide/ROLES-AND-ADMIN.md) and `apps/web/lib/nav.ts`.\n\n';
cv += `${SCREENS.length} screens mapped of ${pages.length} pages in the code · ${ADMIN_FUNCTIONS.length} Admin functions · ${ROLES.length} roles · ${all.length} test cases.\n\n`;
for (const app of ['console', 'partner', 'candidate']) {
  cv += `## ${APP_TITLE[app]}\n\n| Screen | Path | Test cases |\n| --- | --- | --- |\n`;
  for (const s of SCREENS.filter((x) => x.app === app)) cv += `| ${md(s.name)} | \`${s.route}\` | ${links(s.cases)}${s.note ? ` (${md(s.note)})` : ''} |\n`;
  cv += '\n';
}
cv += '## Roles: menu and access denial\n\nMenu = the role sees exactly its menu groups (D-PL-05, D-UI-03). Denial = pages outside the menu show the No access card and APIs refuse (401/403).\n\n| Role | Menu | Denial |\n| --- | --- | --- |\n';
for (const r of ROLES) cv += `| ${r.role} | ${r.menu.length ? links(r.menu) : '– (no menu)'} | ${links(r.denial)} |\n`;
cv += '\n## Admin functions (ROLES-AND-ADMIN.md section 4)\n\n| Function | Where | API | Test cases |\n| --- | --- | --- | --- |\n';
for (const f of ADMIN_FUNCTIONS) cv += `| ${md(f.fn)} | ${md(f.where)} | ${f.api ? `\`${md(f.api)}\`` : ''} | ${links(f.cases)}${f.note ? ` ${md(f.note)}` : ''} |\n`;
cv += '\n## Rules that hold everywhere\n\n| Rule | Test cases |\n| --- | --- |\n';
for (const r of RULES) cv += `| ${md(r.rule)} | ${links(r.cases)} |\n`;
cv += '\n## Not covered yet\n\n';
const uncovered = [...SCREENS.filter((s) => !s.cases.length).map((s) => `Screen \`${s.route}\` (${s.app}) has no test case.`), ...ADMIN_FUNCTIONS.filter((f) => !f.cases.length).map((f) => `${f.fn}: ${f.note ?? 'no test case.'}`), ...unmapped.map((p) => `Page \`${p.route}\` (${p.app}) is in the code but not in coverage.mjs.`), ...GAPS];
cv += uncovered.map((g) => `- ${g}`).join('\n') + '\n';
writeFileSync(join(here, 'COVERAGE.md'), cv);

console.log(`${all.length} test cases, ${DECISIONS.length} decisions, ${api.length} endpoints, ${SCREENS.length}/${pages.length} screens mapped${unmapped.length ? ` (${unmapped.length} unmapped)` : ''} written.`);
